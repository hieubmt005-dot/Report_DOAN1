module address_controller  (

    input clk,
    input rst,

////////////////////////////////////////////////////////////
// ORIGINAL ADDRESSES
////////////////////////////////////////////////////////////

    input [7:0] raddr0,
    input [7:0] raddr1,
    input [7:0] raddr2,
    input [7:0] raddr3,

    input [7:0] waddr0,
    input [7:0] waddr1,

////////////////////////////////////////////////////////////
// RANDOM PERMUTATION FROM RPG
////////////////////////////////////////////////////////////

    input [5:0] addr,
    input [5:0] addr_r12,
    input [6:0] addr_r1,

////////////////////////////////////////////////////////////
// CONTROL
////////////////////////////////////////////////////////////

    input [1:0] line,

    input repl0,
    input repl1,
    input repl2,
    input repl3,
    input repl4,
    input repl5,

////////////////////////////////////////////////////////////
// NEW ADDRESSES
////////////////////////////////////////////////////////////

    output [7:0] raddr0_p,
    output [7:0] raddr1_p,
    output [7:0] raddr2_p,
    output [7:0] raddr3_p,

    output [7:0] waddr0_p,
    output [7:0] waddr1_p

);

////////////////////////////////////////////////////////////
// PART (B)
// SHIFT REGISTERS
////////////////////////////////////////////////////////////

reg [5:0] addr_d1;
reg [5:0] addr_d2;

reg [5:0] addr_r12_d1;

reg [6:0] addr_r1_d1;

always @(posedge clk or posedge rst)
begin

    if(rst)
    begin

        addr_d1 <= 0;
        addr_d2 <= 0;

        addr_r12_d1 <= 0;

        addr_r1_d1 <= 0;

    end

    else
    begin

        addr_d1 <= addr;
        addr_d2 <= addr_d1;

        addr_r12_d1 <= addr_r12;

        addr_r1_d1 <= addr_r1;

    end

end

////////////////////////////////////////////////////////////
// PART (D)
// GENERATION OF addr0 ~ addr5
////////////////////////////////////////////////////////////

wire [7:0] addr0;
wire [7:0] addr1;
wire [7:0] addr2;
wire [7:0] addr3;
wire [7:0] addr4;
wire [7:0] addr5;

////////////////////////////////////////////////////////////
// addr0
// {line, addr}
// 00~3f
// 40~7f
// 80~bf
// c0~ff
////////////////////////////////////////////////////////////

assign addr0 = {line, addr};

////////////////////////////////////////////////////////////
// addr1
////////////////////////////////////////////////////////////

assign addr1 = {2'b00, addr_d1};

////////////////////////////////////////////////////////////
// addr2
// 40~7f
////////////////////////////////////////////////////////////

assign addr2 = {1'b1, addr};

////////////////////////////////////////////////////////////
// addr3
////////////////////////////////////////////////////////////

assign addr3 = {2'b00, addr_d2};

////////////////////////////////////////////////////////////
// addr4
// permutation 00~7f
////////////////////////////////////////////////////////////

assign addr4 = {1'b0, addr_r12_d1};

////////////////////////////////////////////////////////////
// addr5
// permutation 00~7f
////////////////////////////////////////////////////////////

assign addr5 = {1'b0, addr_r1_d1};

////////////////////////////////////////////////////////////
// PART (A)
// SIX 2-to-1 MUXs
////////////////////////////////////////////////////////////

assign raddr0_p = (repl0 == 1'b1) ? addr0 : raddr0;

assign raddr1_p = (repl1 == 1'b1) ? addr1 : raddr1;

assign raddr2_p = (repl2 == 1'b1) ? addr2 : raddr2;

assign raddr3_p = (repl3 == 1'b1) ? addr3 : raddr3;

assign waddr0_p = (repl4 == 1'b1) ? addr4 : waddr0;

assign waddr1_p = (repl5 == 1'b1) ? addr5 : waddr1;

endmodule